export function extractLocation(text) {
  const value = String(text || '');
  const stateMatch = value.match(/\b(andhra pradesh|arunachal pradesh|assam|bihar|chhattisgarh|goa|gujarat|haryana|himachal pradesh|jharkhand|karnataka|kerala|madhya pradesh|maharashtra|manipur|meghalaya|mizoram|nagaland|odisha|punjab|rajasthan|sikkim|tamil nadu|telangana|tripura|uttar pradesh|uttarakhand|west bengal|delhi|jammu and kashmir|ladakh|puducherry)\b/i);
  if (stateMatch?.[1]) return stateMatch[1].replace(/\b\w/g, (letter) => letter.toUpperCase());

  const english = value.match(/(?:live\s+in|staying\s+in|i(?:'m| am)\s+in|near|in)\s+([^.,!?;]{2,60})/i);
  if (english?.[1]) {
    const cleaned = english[1]
      .replace(/\b(?:and|where|but|then|someone|somebody|a|the|they|he|she|i|what should).*$/i, '')
      .trim();
    if (cleaned) return cleaned;
  }

  const indianLanguagePatterns = [
    /(?:मैं|मेरे|मेरा).{0,12}(?:में|से)\s*([\u0900-\u097F\s]{2,30})(?=[।,.!?]|$)/i,
    /(?:ನಾನು|ನನ್ನ).{0,12}(?:ಲ್ಲಿ|ಇಂದ)\s*([\u0C80-\u0CFF\s]{2,30})(?=[।,.!?]|$)/i,
  ];
  for (const pattern of indianLanguagePatterns) {
    const match = value.match(pattern);
    if (match?.[1]) {
      const cleaned = match[1].replace(/[.,!?।]+$/g, '').trim();
      if (cleaned) return cleaned;
    }
  }
  return 'Not stated - confirm before submission';
}

export function extractAmount(text) {
  const value = String(text || '');
  const matches = [
    ...value.matchAll(/(?:₹|rs\.?|inr)\s*([\d,]+(?:\.\d+)?)(?:\s*(crore|lakh|lakhs|thousand))?/gi),
    ...value.matchAll(/([\d,]+(?:\.\d+)?)\s*(crore|lakh|lakhs|thousand|rupees?|रुपये|ರೂಪಾಯಿ)/gi),
  ];

  // Voice transcripts commonly lose "rupees" and currency symbols. Treat a
  // standalone number as an amount only when the incident itself clearly
  // describes a payment/scam context; never run this against protected IDs.
  const financialContext = /\b(?:scam(?:med)?|fraud|cheated|lost|paid|pay|payment|sent|transferred|debited|deducted|scanner|scan|qr|gift\s*cards?|upi|bank|wallet|refund|receive|withdraw)\b/i.test(value);
  if (financialContext) {
    // Keep the amount tied to a payment/scam phrase. This handles voice text
    // such as "I lost 230" while not treating every number as a loss.
    const nearbyAmount = /(?:lost|loss(?:\s+of)?|paid|payment(?:\s+of)?|sent|transferred|debited|deducted|scammed(?:\s+(?:of|for|by))?|cheated(?:\s+(?:of|for|by))?|amount(?:\s+(?:of|was))?|worth|scanner|scan|gift\s*cards?)\D{0,32}?\b(\d{1,3}(?:,\d{2,3})+|\d{1,7})\b/gi;
    for (const match of value.matchAll(nearbyAmount)) {
      matches.push(match);
    }
  }

  if (!matches.length) return 'Not stated';
  return [...new Set(matches.map((m) => `${m[1]}${m[2] ? ` ${m[2]}` : ''}`))].join(', ');
}

function moneyValues(sentence) {
  const values = [];
  for (const match of String(sentence || '').matchAll(/(?:₹|rs\.?|inr)\s*([\d,]+(?:\.\d+)?)/gi)) values.push(match[1]);
  for (const match of String(sentence || '').matchAll(/\b([\d,]+(?:\.\d+)?)\s*(?:rupees?|रुपये|ರೂಪಾಯಿ)\b/gi)) values.push(match[1]);
  const hasFinancialVerb = /\b(?:lost|paid|sent|transferred|debited|deducted|scammed|cheated|payment|amount)\b/i.test(sentence);
  if (hasFinancialVerb) {
    for (const match of String(sentence || '').matchAll(/\b(\d{1,3}(?:,\d{2,3})+|\d{1,7})\b/g)) values.push(match[1]);
  }
  return [...new Set(values)];
}

export function extractTransactions(text) {
  const transactions = [];
  for (const sentence of String(text || '').split(/(?<=[.!?।])\s+/)) {
    const actor = sentence.match(/\b(?:my\s+friend|friend)\s+([A-Z][a-z]{1,40})\b/)?.[1]
      || (/\b(?:i|me|my)\b/i.test(sentence) ? 'You' : 'Not stated');
    const method = sentence.match(/\b(SBI|HDFC|ICICI|Axis|Kotak|Paytm|PhonePe|GPay|Google Pay|BHIM|UPI|bank|wallet)\b/i)?.[1] || '';
    const destination = sentence.match(/\b(?:to|through)\s+(?:a\s+|the\s+)?([^.,;]{2,48})/i)?.[1]
      ?.replace(/\b(?:from|using|via)\b.*$/i, '')
      .trim() || '';
    for (const amount of moneyValues(sentence)) {
      transactions.push({ amount, actor, method, destination });
    }
  }
  return transactions;
}

export function extractPeople(text) {
  const people = [...String(text || '').matchAll(/\b(?:my\s+friend|friend)\s+([A-Z][a-z]{1,40})\b/g)].map((match) => match[1]);
  return [...new Set(people)];
}

export function maskSensitive(text) {
  return String(text || '')
    .replace(/\b(?:\d[ -]?){9,}\b/g, '[number masked]')
    .replace(/\b[A-Z]{2,6}\d{4,}\b/gi, '[account/ref masked]')
    .replace(/\b[\w.+-]+@[\w-]+\.[\w.-]+\b/g, '[email masked]')
    .replace(/\b[\w.-]+@(?:ok\w+|ybl|ibl|axl|paytm|upi)\b/gi, '[UPI ID masked]');
}

